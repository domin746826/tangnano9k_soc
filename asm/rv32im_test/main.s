.section .text
.global _start

# ==============================================================================
# Kompletny Self-Test RV32IM (47 testów)
# MMIO LED: 0xC0000000 (Active-Low: 0 = ON, 1 = OFF)
# PSRAM test addr: 0x00000100
# Rejestr x30 (t5) przechowuje numer aktualnie wykonywanego testu (1..47)
# ==============================================================================

_start:
    # --------------------------------------------------------------------------
    # 1. ADDI
    # --------------------------------------------------------------------------
    addi x30, x0, 1
    addi x1, x0, 123
    addi x2, x1, -23
    addi x3, x0, 100
    bne  x2, x3, fail

    # --------------------------------------------------------------------------
    # 2. SLTI (signed)
    # --------------------------------------------------------------------------
    addi x30, x0, 2
    addi x1, x0, -10
    slti x2, x1, -5          # -10 < -5 -> 1
    slti x3, x1, -20         # -10 < -20 -> 0
    addi x4, x0, 1
    bne  x2, x4, fail
    bne  x3, x0, fail

    # --------------------------------------------------------------------------
    # 3. SLTIU (unsigned)
    # --------------------------------------------------------------------------
    addi x30, x0, 3
    addi x1, x0, -10         # 0xFFFFFFF6 (duza liczba unsigned)
    sltiu x2, x1, 5          # 0xFFFFFFF6 < 5 -> 0
    sltiu x3, x0, 1          # 0 < 1 -> 1
    addi x4, x0, 1
    bne  x2, x0, fail
    bne  x3, x4, fail

    # --------------------------------------------------------------------------
    # 4. XORI
    # --------------------------------------------------------------------------
    addi x30, x0, 4
    addi x1, x0, 0x55
    xori x2, x1, 0xFF
    addi x3, x0, 0xAA
    bne  x2, x3, fail

    # --------------------------------------------------------------------------
    # 5. ORI
    # --------------------------------------------------------------------------
    addi x30, x0, 5
    addi x1, x0, 0x50
    ori  x2, x1, 0x0A
    addi x3, x0, 0x5A
    bne  x2, x3, fail

    # --------------------------------------------------------------------------
    # 6. ANDI
    # --------------------------------------------------------------------------
    addi x30, x0, 6
    addi x1, x0, 0xFF
    andi x2, x1, 0x3C
    addi x3, x0, 0x3C
    bne  x2, x3, fail

    # --------------------------------------------------------------------------
    # 7. SLLI
    # --------------------------------------------------------------------------
    addi x30, x0, 7
    addi x1, x0, 3
    slli x2, x1, 4           # 3 << 4 = 48
    addi x3, x0, 48
    bne  x2, x3, fail

    # --------------------------------------------------------------------------
    # 8. SRLI (logical right shift)
    # --------------------------------------------------------------------------
    addi x30, x0, 8
    addi x1, x0, -16         # 0xFFFFFFF0
    srli x2, x1, 28          # 0x0000000F (15)
    addi x3, x0, 15
    bne  x2, x3, fail

    # --------------------------------------------------------------------------
    # 9. SRAI (arithmetic right shift)
    # --------------------------------------------------------------------------
    addi x30, x0, 9
    addi x1, x0, -64
    srai x2, x1, 4           # -64 >>> 4 = -4
    addi x3, x0, -4
    bne  x2, x3, fail

    # --------------------------------------------------------------------------
    # 10. LUI
    # --------------------------------------------------------------------------
    addi x30, x0, 10
    lui  x1, 0x12345         # 0x12345000
    srli x2, x1, 12
    lui  x3, 0x12
    addi x3, x3, 0x345       # 0x00012345
    bne  x2, x3, fail

    # --------------------------------------------------------------------------
    # 11. AUIPC
    # --------------------------------------------------------------------------
    addi x30, x0, 11
auipc_lbl:
    auipc x1, 0              # x1 = PC(auipc_lbl)
    auipc x2, 0              # x2 = PC(auipc_lbl) + 4
    sub   x3, x2, x1
    addi  x4, x0, 4
    bne   x3, x4, fail

    # --------------------------------------------------------------------------
    # 12. ADD
    # --------------------------------------------------------------------------
    addi x30, x0, 12
    addi x1, x0, 450
    addi x2, x0, 550
    add  x3, x1, x2
    addi x4, x0, 1000
    bne  x3, x4, fail

    # --------------------------------------------------------------------------
    # 13. SUB
    # --------------------------------------------------------------------------
    addi x30, x0, 13
    addi x1, x0, 300
    addi x2, x0, 450
    sub  x3, x1, x2
    addi x4, x0, -150
    bne  x3, x4, fail

    # --------------------------------------------------------------------------
    # 14. SLL
    # --------------------------------------------------------------------------
    addi x30, x0, 14
    addi x1, x0, 7
    addi x2, x0, 5
    sll  x3, x1, x2          # 7 << 5 = 224
    addi x4, x0, 224
    bne  x3, x4, fail

    # --------------------------------------------------------------------------
    # 15. SLT (signed)
    # --------------------------------------------------------------------------
    addi x30, x0, 15
    addi x1, x0, -100
    addi x2, x0, 10
    slt  x3, x1, x2          # -100 < 10 -> 1
    slt  x4, x2, x1          # 10 < -100 -> 0
    addi x5, x0, 1
    bne  x3, x5, fail
    bne  x4, x0, fail

    # --------------------------------------------------------------------------
    # 16. SLTU (unsigned)
    # --------------------------------------------------------------------------
    addi x30, x0, 16
    addi x1, x0, -100        # 0xFFFFFF9C
    addi x2, x0, 10
    sltu x3, x1, x2          # 0xFFFFFF9C < 10 -> 0
    sltu x4, x2, x1          # 10 < 0xFFFFFF9C -> 1
    addi x5, x0, 1
    bne  x3, x0, fail
    bne  x4, x5, fail

    # --------------------------------------------------------------------------
    # 17. XOR
    # --------------------------------------------------------------------------
    addi x30, x0, 17
    addi x1, x0, 0x3C
    addi x2, x0, 0xFF
    xor  x3, x1, x2
    addi x4, x0, 0xC3
    bne  x3, x4, fail

    # --------------------------------------------------------------------------
    # 18. SRL
    # --------------------------------------------------------------------------
    addi x30, x0, 18
    addi x1, x0, -32         # 0xFFFFFFE0
    addi x2, x0, 29
    srl  x3, x1, x2          # 7
    addi x4, x0, 7
    bne  x3, x4, fail

    # --------------------------------------------------------------------------
    # 19. SRA
    # --------------------------------------------------------------------------
    addi x30, x0, 19
    addi x1, x0, -128
    addi x2, x0, 3
    sra  x3, x1, x2          # -16
    addi x4, x0, -16
    bne  x3, x4, fail

    # --------------------------------------------------------------------------
    # 20. OR
    # --------------------------------------------------------------------------
    addi x30, x0, 20
    addi x1, x0, 0x101
    addi x2, x0, 0x010
    or   x3, x1, x2
    addi x4, x0, 0x111
    bne  x3, x4, fail

    # --------------------------------------------------------------------------
    # 21. AND
    # --------------------------------------------------------------------------
    addi x30, x0, 21
    addi x1, x0, 0x1FF
    addi x2, x0, 0x0A5
    and  x3, x1, x2
    addi x4, x0, 0x0A5
    bne  x3, x4, fail

    # --------------------------------------------------------------------------
    # 22. BEQ
    # --------------------------------------------------------------------------
    addi x30, x0, 22
    addi x1, x0, 77
    addi x2, x0, 77
    addi x3, x0, 88
    beq  x1, x3, fail        # nie powinien skoczyc
    beq  x1, x2, beq_ok      # powinien skoczyc
    jal  x0, fail
beq_ok:

    # --------------------------------------------------------------------------
    # 23. BNE
    # --------------------------------------------------------------------------
    addi x30, x0, 23
    addi x1, x0, 12
    addi x2, x0, 34
    bne  x1, x1, fail        # nie powinien skoczyc
    bne  x1, x2, bne_ok      # powinien skoczyc
    jal  x0, fail
bne_ok:

    # --------------------------------------------------------------------------
    # 24. BLT (signed)
    # --------------------------------------------------------------------------
    addi x30, x0, 24
    addi x1, x0, -5
    addi x2, x0, 3
    blt  x2, x1, fail        # 3 < -5 -> false
    blt  x1, x2, blt_ok      # -5 < 3 -> true
    jal  x0, fail
blt_ok:

    # --------------------------------------------------------------------------
    # 25. BGE (signed)
    # --------------------------------------------------------------------------
    addi x30, x0, 25
    addi x1, x0, -5
    addi x2, x0, 3
    bge  x1, x2, fail        # -5 >= 3 -> false
    bge  x1, x1, bge_step    # -5 >= -5 -> true
    jal  x0, fail
bge_step:
    bge  x2, x1, bge_ok      # 3 >= -5 -> true
    jal  x0, fail
bge_ok:

    # --------------------------------------------------------------------------
    # 26. BLTU (unsigned)
    # --------------------------------------------------------------------------
    addi x30, x0, 26
    addi x1, x0, 5
    addi x2, x0, -1          # 0xFFFFFFFF
    bltu x2, x1, fail        # 0xFFFFFFFF < 5 -> false
    bltu x1, x2, bltu_ok     # 5 < 0xFFFFFFFF -> true
    jal  x0, fail
bltu_ok:

    # --------------------------------------------------------------------------
    # 27. BGEU (unsigned)
    # --------------------------------------------------------------------------
    addi x30, x0, 27
    addi x1, x0, 5
    addi x2, x0, -1          # 0xFFFFFFFF
    bgeu x1, x2, fail        # 5 >= 0xFFFFFFFF -> false
    bgeu x2, x1, bgeu_ok     # 0xFFFFFFFF >= 5 -> true
    jal  x0, fail
bgeu_ok:

    # --------------------------------------------------------------------------
    # 28. JAL
    # --------------------------------------------------------------------------
    addi x30, x0, 28
    auipc x2, 0              # x2 = PC
    addi  x2, x2, 12         # oczekiwany adres powrotu (PC + 12)
    jal   x1, jal_target     # x1 = PC + 4
    jal   x0, fail
jal_target:
    bne   x1, x2, fail

    # --------------------------------------------------------------------------
    # 29. JALR
    # --------------------------------------------------------------------------
    addi x30, x0, 29
    auipc x1, 0              # x1 = PC
    addi  x3, x1, 16         # oczekiwany link (PC + 16)
    addi  x1, x1, 21         # cel skoku + 1 (test obcinania LSB: & ~1)
    jalr  x2, 0(x1)
    jal   x0, fail
jalr_target:
    bne   x2, x3, fail

    # --------------------------------------------------------------------------
    # Przygotowanie adresu bazowego w PSRAM (0x00000100) dla testow pamieci
    # --------------------------------------------------------------------------
    addi x10, x0, 0x100      # baza w PSRAM = 0x00000100

    # --------------------------------------------------------------------------
    # 30. SW i 31. LW (32-bit)
    # --------------------------------------------------------------------------
    addi x30, x0, 30
    lui  x1, 0xDEADB
    addi x1, x1, -273        # 0xDEADB000 - 0x111 = 0xDEADAEF... zrobmy:
    lui  x1, 0x12345
    addi x1, x1, 0x678       # x1 = 0x12345678
    sw   x1, 0(x10)          # zapis do PSRAM[0x100]

    addi x30, x0, 31
    lw   x2, 0(x10)
    bne  x1, x2, fail

    # --------------------------------------------------------------------------
    # 32. SH (16-bit Store Halfword - dolna i gorna polowa)
    # --------------------------------------------------------------------------
    addi x30, x0, 32
    sw   x0, 4(x10)          # wyzeruj slowo PSRAM[0x104]
    addi x1, x0, -100        # 0xFFFFFF9C -> polslowo 0xFF9C
    addi x2, x0, 0x123       # polslowo 0x0123
    sh   x1, 4(x10)          # dolne 16 bitow = 0xFF9C
    sh   x2, 6(x10)          # gorne 16 bitow = 0x0123
    # w pamieci pod 0x104 powinno byc 0x0123FF9C

    # --------------------------------------------------------------------------
    # 33. LH (16-bit Load Halfword Signed)
    # --------------------------------------------------------------------------
    addi x30, x0, 33
    lh   x3, 4(x10)          # powinno wczytac 0xFF9C z rozszerzeniem znaku -> -100
    lh   x4, 6(x10)          # powinno wczytac 0x0123 -> 0x123
    bne  x3, x1, fail
    bne  x4, x2, fail

    # --------------------------------------------------------------------------
    # 34. LHU (16-bit Load Halfword Unsigned)
    # --------------------------------------------------------------------------
    addi x30, x0, 34
    lhu  x3, 4(x10)          # powinno wczytac 0x0000FF9C (65436)
    lui  x5, 0x10
    addi x5, x5, -100        # 65536 - 100 = 65436 (0x0000FF9C)
    bne  x3, x5, fail

    # --------------------------------------------------------------------------
    # 35. SB (8-bit Store Byte - wszystkie 4 pozycje addr[1:0] = 0, 1, 2, 3)
    # --------------------------------------------------------------------------
    addi x30, x0, 35
    sw   x0, 8(x10)          # wyzeruj PSRAM[0x108]
    addi x1, x0, 0x11
    addi x2, x0, -16         # 0xF0 (-16)
    addi x3, x0, 0x33
    addi x4, x0, -1          # 0xFF (-1)
    sb   x1, 8(x10)          # bajt 0 (addr[1:0] = 00)
    sb   x2, 9(x10)          # bajt 1 (addr[1:0] = 01)
    sb   x3, 10(x10)         # bajt 2 (addr[1:0] = 10)
    sb   x4, 11(x10)         # bajt 3 (addr[1:0] = 11)

    # --------------------------------------------------------------------------
    # 36. LB (8-bit Load Byte Signed)
    # --------------------------------------------------------------------------
    addi x30, x0, 36
    lb   x5, 8(x10)          # 0x11
    lb   x6, 9(x10)          # -16 (sign-extended)
    lb   x7, 10(x10)         # 0x33
    lb   x8, 11(x10)         # -1  (sign-extended)
    bne  x5, x1, fail
    bne  x6, x2, fail
    bne  x7, x3, fail
    bne  x8, x4, fail

    # --------------------------------------------------------------------------
    # 37. LBU (8-bit Load Byte Unsigned)
    # --------------------------------------------------------------------------
    addi x30, x0, 37
    lbu  x5, 9(x10)          # 0x000000F0 (240)
    lbu  x6, 11(x10)         # 0x000000FF (255)
    addi x7, x0, 240
    addi x8, x0, 255
    bne  x5, x7, fail
    bne  x6, x8, fail

    # ==========================================================================
    # ROZSZERZENIE M (MUL / DIV / REM)
    # ==========================================================================

    # --------------------------------------------------------------------------
    # 38. MUL (dolne 32 bity)
    # --------------------------------------------------------------------------
    addi x30, x0, 38
    addi x1, x0, 123
    addi x2, x0, -45
    mul  x3, x1, x2          # 123 * (-45) = -5535 (0xFFFFEA61)
    lui  x4, 0xFFFFF
    addi x4, x4, -1439       # -4096 - 1439 = -5535
    bne  x3, x4, fail

    # --------------------------------------------------------------------------
    # 39. MULH (signed x signed -> gorne 32 bity)
    # --------------------------------------------------------------------------
    addi x30, x0, 39
    lui  x1, 0x40000         # 0x40000000 (2^30)
    addi x2, x0, -8          # -8
    mulh x3, x1, x2          # (2^30 * -8) >> 32 = -2
    addi x4, x0, -2
    bne  x3, x4, fail

    # --------------------------------------------------------------------------
    # 40. MULHSU (signed x unsigned -> gorne 32 bity)
    # --------------------------------------------------------------------------
    addi x30, x0, 40
    addi   x1, x0, -2        # signed: -2
    lui    x2, 0x80000       # unsigned: 0x80000000 (2^31)
    mulhsu x3, x1, x2        # (-2 * 2^31) = -2^32 -> gorne 32 bity = -1 (0xFFFFFFFF)
    addi   x4, x0, -1
    bne    x3, x4, fail

    # --------------------------------------------------------------------------
    # 41. MULHU (unsigned x unsigned -> gorne 32 bity)
    # --------------------------------------------------------------------------
    addi x30, x0, 41
    lui   x1, 0x80000        # 2^31
    lui   x2, 0x80000        # 2^31
    mulhu x3, x1, x2         # (2^31 * 2^31) >> 32 = 2^30 (0x40000000)
    lui   x4, 0x40000
    bne   x3, x4, fail

    # --------------------------------------------------------------------------
    # 42. DIV (signed)
    # --------------------------------------------------------------------------
    addi x30, x0, 42
    addi x1, x0, -100
    addi x2, x0, 7
    div  x3, x1, x2          # -100 / 7 = -14
    addi x4, x0, -14
    bne  x3, x4, fail

    # --------------------------------------------------------------------------
    # 43. DIVU (unsigned)
    # --------------------------------------------------------------------------
    addi x30, x0, 43
    addi x1, x0, -2          # 0xFFFFFFFE (4294967294)
    addi x2, x0, 2
    divu x3, x1, x2          # 0x7FFFFFFF
    lui  x4, 0x80000
    addi x4, x4, -1          # 0x7FFFFFFF
    bne  x3, x4, fail

    # --------------------------------------------------------------------------
    # 44. REM (signed)
    # --------------------------------------------------------------------------
    addi x30, x0, 44
    addi x1, x0, -100
    addi x2, x0, 7
    rem  x3, x1, x2          # -100 % 7 = -2 (znak reszty = znak dzielnej!)
    addi x4, x0, -2
    bne  x3, x4, fail

    # --------------------------------------------------------------------------
    # 45. REMU (unsigned)
    # --------------------------------------------------------------------------
    addi x30, x0, 45
    lui  x1, 0x80000         # 2147483648
    addi x1, x1, 5           # 2147483653
    addi x2, x0, 10
    remu x3, x1, x2          # 2147483653 % 10 = 3
    addi x4, x0, 3
    bne  x3, x4, fail

    # --------------------------------------------------------------------------
    # 46. Dzielenie przez zero (Specyfikacja RISC-V: DIV -> -1, REM -> dzielna)
    # --------------------------------------------------------------------------
    addi x30, x0, 46
    addi x1, x0, 1234
    div  x2, x1, x0          # 1234 / 0 -> -1 (0xFFFFFFFF)
    rem  x3, x1, x0          # 1234 % 0 -> 1234
    addi x4, x0, -1
    bne  x2, x4, fail
    bne  x3, x1, fail

    # --------------------------------------------------------------------------
    # 47. Signed Overflow (-2^31 / -1 -> -2^31, reszta -> 0)
    # --------------------------------------------------------------------------
    addi x30, x0, 47
    lui  x1, 0x80000         # -2^31 (0x80000000)
    addi x2, x0, -1          # -1
    div  x3, x1, x2          # wynik: 0x80000000
    rem  x4, x1, x2          # reszta: 0
    bne  x3, x1, fail
    bne  x4, x0, fail

    # ==========================================================================
    # SUKCES! Wszystkie 47 testow przeszlo -> zapal wszystkie 6 diod (kod 63)
    # ==========================================================================
    addi x30, x0, 63         # 6'b111111 (wszystkie diody swieca po negacji)

fail:
    lui  x28, 0xC0000        # Adres MMIO LED: 0xC0000000
    xori x29, x30, -1        # Negacja bitowa dla diod active-low (0 = swieci)
    sw   x29, 0(x28)         # Wystaw wynik na LED-y
loop_forever:
    jal  x0, loop_forever